// Regenerates docs/exnames-review.md from locales/exnames.fa.js + the exercise dataset.
// Run: node scripts/gen-exnames-review.mjs   (always regenerate — never hand-edit the doc)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const pack = (await import(new URL('../frontend/src/locales/exnames.fa.js', import.meta.url).href)).default
const { EXDB } = await import(new URL('../frontend/src/lib/exercises-data.js', import.meta.url).href)
const EXIDX = new Map(EXDB.map(e => [e.id, e]))

const rows = Object.entries(pack)
  .map(([id, e]) => ({ id, ...e, bp: EXIDX.get(id)?.bp || '?', en: EXIDX.get(id)?.n || '?' }))
  .sort((a, b) => a.bp.localeCompare(b.bp) || a.en.localeCompare(b.en))

const esc = s => String(s).replace(/\|/g, '\\|')
let out = `# Persian exercise names — review sheet

> لطفاً پیش از merge توسط فردی آشنا به اصطلاحات بدنسازی مرور شود.
> Generated by \`scripts/gen-exnames-review.mjs\` from \`locales/exnames.fa.js\` — regenerate, never hand-edit.
> ${rows.length} exercises covered · dataset: hasaneyldrm/exercises-dataset

| id | نام انگلیسی | نام فارسی | aliasها | گروه |
|---|---|---|---|---|
`
for (const r of rows) {
  out += `| ${r.id} | ${esc(r.en)} | ${esc(r.n)} | ${esc((r.a || []).join('، ')) || '—'} | ${r.bp} |\n`
}
fs.writeFileSync(path.join(root, 'docs', 'exnames-review.md'), out)
console.log(`docs/exnames-review.md written — ${rows.length} rows`)
